    """An upgrade keeps .env byte for byte while web research is off: research.ps1 -Enable creates the secret."""
    ps1 = script("init-env.ps1")
    assert "SEARXNG_SECRET" not in _line(ps1, "$upgradeKeys")
    sh = (ROOT / "scripts" / "init-env.sh").read_text()
    assert "SEARXNG_SECRET" not in _line(sh, "for spec in")
