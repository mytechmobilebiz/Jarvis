def test_research_enable_creates_a_missing_secret_after_the_env_copy_and_never_prints_it():
    text = script("research.ps1")
    enable = text[text.index("if ($Enable) {"):text.index("if ($Disable) {")]
    created = enable.index("New-Secret 32")
    assert created < enable.index("Set-Secret $new") and created < enable.index("Set-ComposeFile $wanted $new")
    # Compose's check sees it through this process only; .env is the only source when start.ps1 runs.
    check = enable.index("docker compose config --services")
    assert enable.index("if ($new) { $env:SEARXNG_SECRET = $new }") < check
    assert check < enable.index("Remove-Item Env:COMPOSE_FILE, Env:SEARXNG_SECRET")
    assert enable.index("Remove-Variable new") < enable.index('& (Join-Path $PSScriptRoot "start.ps1") -NoBuild')
    assert enable.rindex("Remove-Item Env:SEARXNG_SECRET") < enable.index('& (Join-Path $PSScriptRoot "start.ps1")')
    # A short value is never replaced quietly, and two lines refuse.
    assert "-RotateSecret, then run -Enable again" in enable and "SEARXNG_SECRET more than once" in enable
    assert 'Write-Host "Added SEARXNG_SECRET to .env (not shown); no stored data depends on it."' in enable
    # Each change is one write, after a copy of .env.
    writer = text[text.index("function Write-EnvLines"):text.index("function Set-ComposeFile")]
    assert writer.index("Copy-Item -LiteralPath $envFile") < writer.index("WriteAllText")
    # The temporary file is written once (outside Windows through a stream created with .env's mode) and replaces
    # .env once.
    assert writer.count("WriteAllText($tmp, ") == writer.count("WriteAllText") == 1
    assert writer.count("[IO.File]::Replace(") == 1
    for name in ("Set-ComposeFile", "Set-Secret"):
        body = text[text.index(f"function {name}"):]
        body = body[:body.index("\n}\n")]
        assert body.count("Write-EnvLines") == 1, name
    assert "export\\s+)?SEARXNG_SECRET" in text  # "export SEARXNG_SECRET=" counts as a line too


