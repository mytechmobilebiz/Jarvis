    install = script("install.ps1")
    assert '& (Join-Path $scripts "init-env.ps1") -AddMissing' in install and "SEARXNG" not in install
    preflight = script("preflight.ps1")
    for name in ("$required", "$addable"):
        assert "SEARXNG_SECRET" not in _line(preflight, name), name
    # Only a warning, and only while the search service is switched on in .env.
    checks = [line for line in preflight.splitlines() if "SEARXNG_SECRET" in line and not line.lstrip().startswith("#")]
    assert checks and all("Bad " not in line for line in checks)
    assert "docker-compose\\.research\\.yml" in preflight[preflight.index("$envValues[\"COMPOSE_FILE\"]"):]


