# Writes command-center\.env with fresh random secrets (Windows / PowerShell).
# Refuses to overwrite an existing .env. Read-only apart from creating that file.
#
#   .\scripts\init-env.ps1 [-AdminEmail you@example.com]
param([string]$AdminEmail = "admin@infinitemarketing.local")

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
$envFile = Join-Path $root ".env"
if (Test-Path $envFile) { Write-Host ".env already exists; not overwriting it." -ForegroundColor Yellow; exit 1 }

function New-Secret([int]$bytes) {
  $buffer = New-Object byte[] $bytes
  [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($buffer)
  return ([Convert]::ToBase64String($buffer)).TrimEnd("=").Replace("+", "-").Replace("/", "_")
}

$adminPassword = New-Secret 18
$n8nPassword = (New-Secret 18) + "A1"   # n8n wants a digit and a capital letter
$stamp = (Get-Date).ToUniversalTime().ToString("yyyy-MM-ddTHH:mm:ssZ")

$content = @"
# Generated by scripts/init-env.ps1 on $stamp. Keep this file private; never commit it.
ENVIRONMENT=production
ADMIN_EMAIL=$AdminEmail
ADMIN_PASSWORD=$adminPassword

POSTGRES_PASSWORD=$(New-Secret 24)
CC_DB_PASSWORD=$(New-Secret 24)
N8N_DB_PASSWORD=$(New-Secret 24)

CC_SERVICE_TOKEN=$(New-Secret 32)
N8N_WEBHOOK_SECRET=$(New-Secret 32)
N8N_ENCRYPTION_KEY=$(New-Secret 32)
N8N_OWNER_PASSWORD=$n8nPassword

# Set to true once the dashboard is served over HTTPS.
COOKIE_SECURE=false

# Optional: Claude for planning and summaries (metered). Without it the
# supervisor plans with deterministic rules.
ANTHROPIC_API_KEY=
LLM_MODEL=claude-opus-5-5
LLM_DAILY_REQUEST_CAP=200

TZ=America/New_York
DASHBOARD_PORT=8090
N8N_PORT=5680
"@

# UTF-8 without BOM and LF line endings, which Docker Compose reads cleanly.
[System.IO.File]::WriteAllText($envFile, ($content -replace "`r`n", "`n"), (New-Object System.Text.UTF8Encoding $false))
Write-Host "Wrote $envFile"
Write-Host "Dashboard sign-in: $AdminEmail / $adminPassword"
Write-Host "n8n sign-in:       $AdminEmail / $n8nPassword"
Write-Host "Back up N8N_ENCRYPTION_KEY somewhere safe: without it n8n cannot decrypt its stored credentials."
exit 0
