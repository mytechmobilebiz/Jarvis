#!/usr/bin/env bash
# Writes command-center/.env with fresh random secrets. Refuses to overwrite.
#
#   ./scripts/init-env.sh [admin-email]
#
# Prints the generated admin and n8n passwords once; they are also in .env
# (which git ignores). Change them after the first sign-in if you prefer.
set -euo pipefail
cd "$(dirname "$0")/.."

if [[ -e .env ]]; then
  echo ".env already exists; not overwriting it." >&2
  exit 1
fi

secret() { python3 -c "import secrets; print(secrets.token_urlsafe($1))"; }

ADMIN_EMAIL="${1:-admin@infinitemarketing.local}"
ADMIN_PASSWORD="$(secret 18)"
N8N_OWNER_PASSWORD="$(secret 18)A1"   # n8n wants a digit and a capital letter

umask 077
cat > .env <<EOF
# Generated by scripts/init-env.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Keep this file private.
ENVIRONMENT=production
ADMIN_EMAIL=${ADMIN_EMAIL}
ADMIN_PASSWORD=${ADMIN_PASSWORD}

POSTGRES_PASSWORD=$(secret 24)
CC_DB_PASSWORD=$(secret 24)
N8N_DB_PASSWORD=$(secret 24)

CC_SERVICE_TOKEN=$(secret 32)
CC_SECRETS_KEY=$(secret 32)
N8N_WEBHOOK_SECRET=$(secret 32)
N8N_ENCRYPTION_KEY=$(secret 32)
N8N_OWNER_PASSWORD=${N8N_OWNER_PASSWORD}

# Set to true once the dashboard is served over HTTPS.
COOKIE_SECURE=false

# Optional: Claude for planning and summaries (metered). Without it the
# supervisor plans with deterministic rules.
ANTHROPIC_API_KEY=
LLM_MODEL=claude-opus-5-5
LLM_DAILY_REQUEST_CAP=200

TZ=America/New_York
DASHBOARD_PORT=8090
N8N_PORT=5680
EOF

echo "Wrote $(pwd)/.env"
echo "Dashboard sign-in: ${ADMIN_EMAIL} / ${ADMIN_PASSWORD}"
echo "n8n sign-in:       ${ADMIN_EMAIL} / ${N8N_OWNER_PASSWORD}"
